#!/usr/bin/env node
// Writes examples/before-and-after.md: every post on the site's practice feed, before and after the goblin.
// The posts come straight from src/page.html and the translations from the real engine, and a test checks
// the committed file is current, so this gallery can't drift from what the goblin actually does.
//
//   npm run examples
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';
import '../src/goblin.js';

const G = globalThis.SlopGoblin;
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(ROOT, 'examples', 'before-and-after.md');

/* The practice feed's posts, read out of src/page.html. */
export function practicePosts() {
  const page = readFileSync(join(ROOT, 'src', 'page.html'), 'utf8');
  const unquote = s => s.replace(/\\'/g, "'").replace(/\\n/g, '\n');
  const posts = [];
  const re = /\{ n: '((?:[^'\\]|\\.)*)', i: '[^']*', c: '[^']*', h: '((?:[^'\\]|\\.)*)'[\s\S]*?b: '((?:[^'\\]|\\.)*)' \}/g;
  let m;
  while ((m = re.exec(page))) posts.push({ name: unquote(m[1]), headline: unquote(m[2]), body: unquote(m[3]) });
  return posts;
}

/* A blockquote that keeps the post's line breaks (GitHub would otherwise run them together). */
const quote = text => {
  const lines = text.split('\n');
  return lines.map((l, i) => {
    if (!l) return '>';
    const hard = i + 1 < lines.length && lines[i + 1] ? '\\' : '';
    return '> ' + l + hard;
  }).join('\n');
};

export function render() {
  const posts = practicePosts();
  const parts = [
    '# Before and after',
    '',
    'Every post on the [practice feed](https://slopgoblin.pharmatools.ai), run through the goblin with Translator on.',
    'The people are invented; the vocabulary is real. This file is generated by `npm run examples`, so it always',
    'matches what the goblin does today.',
    ''
  ];
  let total = 0, totalServings = 0;
  for (const p of posts) {
    const bites = G.bites(p.body);
    const servings = bites.reduce((n, b) => n + b.servings, 0);
    total += bites.length; totalServings += servings;
    parts.push(`## ${p.name}`, '', `*${p.headline}*`, '', '**Before**', '', quote(p.body), '',
      '**After**', '', quote(G.translate(p.body)), '',
      `**The bill:** ${bites.length} bites · ${servings} servings · girth: ${G.girthFor(servings)}`, '',
      '<details><summary>Every bite</summary>', '',
      '| Ate | Spat back | Servings |', '| --- | --- | ---: |',
      ...bites.map(b => `| ${b.text} | ${b.plain} | ${b.servings} |`), '', '</details>', '');
  }
  parts.push('---', '', `${posts.length} posts · ${total} bites · ${totalServings} servings · final girth: **${G.girthFor(totalServings)}**`, '');
  return parts.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  writeFileSync(OUT, render());
  console.log('wrote examples/before-and-after.md');
}
